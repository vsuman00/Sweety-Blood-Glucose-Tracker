import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {makePool,migrate} from '../server/database.js';
import {createApp} from '../server/app.js';
const url=process.env.TEST_DATABASE_URL;
if(!url||!new URL(url).pathname.endsWith('_test')||url===process.env.DATABASE_URL)throw new Error('Use a separate test database ending in _test.');
const pool=makePool(url);await migrate(pool);
const origin='http://127.0.0.1:3002';
const app=createApp({pool,secret:'browser-test-only-secret-at-least-32-chars',origin});
const server=await new Promise(resolve=>{const server=app.listen(3002,'127.0.0.1',()=>resolve(server));});
const email=`browser-${Date.now()}@example.test`;
let browser;
try{
 browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin);
 await page.getByRole('button',{name:'New here? Create an account'}).click();
 await page.getByLabel('Name',{exact:true}).fill('Browser Tester');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill('synthetic-password');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('heading',{name:'Hello, Browser Tester.'}).waitFor();
 await page.getByRole('heading',{name:'A fresh page for this day'}).waitFor();
 await page.getByLabel('Glucose (mg/dl)',{exact:true}).fill('100');
 await page.getByRole('button',{name:'Add reading',exact:true}).click();
 await page.getByText('Reading added.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Edit Morning (fasting)',exact:true}).waitFor();
 assert.equal(await page.locator('.daily-panel .stats dd').nth(2).innerText(),'100.0');
 await page.getByLabel('Glucose (mg/dl)',{exact:true}).fill('111');
 await page.getByRole('button',{name:'Add reading',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'already have a reading'}).waitFor();
 await page.getByRole('button',{name:'Edit Morning (fasting)',exact:true}).click();
 await page.getByLabel('Glucose (mg/dl)',{exact:true}).fill('123');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await page.getByText('Reading updated.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Delete Morning (fasting)',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').count(),0);
 await page.getByRole('button',{name:'Delete Morning (fasting)',exact:true}).click();
 await page.getByRole('button',{name:'Delete reading',exact:true}).click();
 await page.getByText('Reading deleted.',{exact:true}).waitFor();
 await page.getByRole('heading',{name:'A fresh page for this day'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
 await page.getByRole('button',{name:'Log out',exact:true}).click();
 await page.getByRole('heading',{name:'Welcome back'}).waitFor();
 await page.reload();await page.getByRole('heading',{name:'Welcome back'}).waitFor();
 assert.deepEqual(errors,[]);console.log('Browser journey passed: registration, empty state, create, duplicate error, edit, rounding, delete dialog, mobile layout, logout.');
}finally{
 await browser?.close();await pool.query('DELETE FROM users WHERE email=$1',[email]);
 app.locals.sessionStore.close();await new Promise(resolve=>server.close(resolve));await pool.end();
}
